// תפקיד: הגדרת כל ה"ספירות" (Enums) שבהן המערכת משתמשת.
//         Enum הוא סוג משתנה מיוחד שמאפשר לבחור מתוך רשימה קבועה של ערכים.
//         במקום לכתוב מחרוזת כמו "Admin" (שעלולה לכלול שגיאות כתיב),
//         משתמשים ב-UserRole.Admin - ברור, בטוח, וללא שגיאות.
// =====================================

using System;

namespace AppointmentManager.Domain
{
    /// <summary>
    /// מגדיר את סוגי התפקידים האפשריים של משתמשים במערכת.
    /// לכל משתמש יש תפקיד אחד בלבד שקובע מה הוא מורשה לעשות.
    /// </summary>
    public enum UserRole
    {
        /// <summary>
        /// מנהל/ת - יש לו/ה גישה מלאה לכל הפונקציות:
        /// קביעת תורים ללקוחות, עריכת משמרות, ניהול הגדרות, צפייה בדוחות.
        /// </summary>
        Admin,

        /// <summary>
        /// לקוח/ה רשומ/ה - נרשם/ה בעצמו/ה למערכת.
        /// יכול/ה לקבוע תורים, לראות היסטוריה אישית, ולבטל תורים בהתאם למדיניות.
        /// </summary>
        Client,

        /// <summary>
        /// לקוח/ה מנוהל/ת - נוצר/ה אוטומטית על ידי המנהל/ת
        /// כשמזינים שם וטלפון ידנית (ללא הרשמה עצמאית).
        /// לקוח זה אינו מקבל אימיילים ואינו יכול להתחבר למערכת.
        /// </summary>
        ManagedClient
    }

    /// <summary>
    /// מגדיר את המצבים האפשריים של תור ביומן.
    /// כל תור מתחיל במצב Scheduled ויכול לעבור ל-Cancelled.
    /// </summary>
    public enum AppointmentStatus
    {
        /// <summary>
        /// תור קבוע ופעיל - ממתין להתקיימות.
        /// </summary>
        Scheduled,

        /// <summary>
        /// תור שבוטל - על ידי הלקוח/ה או על ידי המנהל/ת.
        /// התור נשמר בבסיס הנתונים אך אינו מופיע ביומן הפעיל.
        /// </summary>
        Cancelled
    }

    /// <summary>
    /// מגדיר את המצבים האפשריים של הצעת החלפת תור בלוח ההעברה.
    /// </summary>
    public enum SwapOfferStatus
    {
        /// <summary>הצעה פעילה – מוצגת בלוח וממתינה לקבלה.</summary>
        Active = 0,

        /// <summary>הצעה שנתקבלה – התור הועבר ללקוחה אחרת.</summary>
        Accepted = 1,

        /// <summary>הצעה שבוטלה על ידי המציעה.</summary>
        Cancelled = 2
    }
}
